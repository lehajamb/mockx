#!/usr/bin/env python3
"""Run every no-hardware check and write docs/verification-report.md (plus raw reports under docs/reports/)."""
import os, sys, re, json, subprocess, collections, shutil, datetime
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..'); HW = os.path.join(ROOT, 'hw'); DOCS = os.path.join(ROOT, 'docs'); REP = os.path.join(DOCS, 'reports')
os.makedirs(REP, exist_ok=True)
TODAY = '2026-11-16'
# DRC categories that are accepted, with the reason.  Anything not listed here is an unwaived error.
WAIVERS = {
    'lib_footprint_mismatch': 'Footprints are edited after loading from the library: reference text moved to the Fab layer and value text hidden. Pads and courtyards are unchanged.',
    'lib_footprint_issues': 'The KiCad 7 standalone DRC does not load the project footprint table, so library lookups fail. Footprint geometry itself is checked by the other rules.',
    'silk_over_copper': 'Library silkscreen of connectors crosses exposed pads; fabricators clip silkscreen to the mask opening.',
    'silk_overlap': 'Library silkscreen outlines of adjacent parts touch at 0.45 mm placement spacing. Cosmetic.',
    'silk_edge_clearance': 'Edge connectors (RJ45, USB, SMA, microSD) have library silkscreen at or beyond the board edge. Cosmetic; clipped at the edge.',
    'copper_edge_clearance': ('Pads of edge-mounted connectors only (J5 edge-launch SMA, J12 microSD shell tabs): they sit at the board edge by design of the part. Tracks and vias are not covered by this waiver.', r'Pad \S+ \[[^\]]*\] of (J5|J12) '),
    'hole_clearance': ('USB-C receptacles J3/J10 only: the non-plated locating-peg holes of the GCT USB4105 land pattern sit next to the GND pads A1/B12 of the same footprint. Same net as the shell, no other copper involved. Fab note: follow the GCT land pattern.', r'NPTH pad of (J3|J10)\b[\s\S]*Pad (A1|A12|B1|B12) \[GND\] of (J3|J10)'),
    'courtyards_overlap': 'Edge connectors overhang; courtyards of the SoM socket and parts next to the module outline touch the nominal module keep-out drawn in the socket footprint.',
    'pth_inside_courtyard': 'GND stitching vias and plated holes inside connector courtyards (under RJ45 bodies). No mechanical conflict: the bodies stand on their own pins.',
    'npth_inside_courtyard': 'Locating-peg holes of one connector fall inside its own or the neighbouring courtyard.',
    'holes_co_located': 'Library footprint has duplicate mounting pads.',
    'starved_thermal': 'Through-hole GND pins with fewer than two thermal spokes still connect on two plane layers.',
    'text_height': 'Fab-layer reference text is 0.6 mm by choice (assembly drawing only).', 'text_thickness': 'Same as text_height.',
    'isolated_copper': 'Small pour islands are removed at fill time; any reported are informational.',
    'via_dangling': 'Stitching via that touches only the inner GND planes at that location. It still ties In1 to In2.',
    'track_dangling': 'Short stubs left by the autorouter at pad entries; no electrical effect at these lengths. Listed for cleanup in layout review.',
    'missing_courtyard': 'Mounting holes, fiducials and test pads from the library have no courtyard.',
    'footprint_type_mismatch': 'Library attribute (SMD vs through-hole) of connectors with mixed pads.',
    'drill_out_of_range': 'Library connector slots/pegs below the generic 0.3 mm minimum are non-plated tooling features.',
    'solder_mask_bridge': 'Adjacent pads of the same footprint share a mask opening at 0.5 mm pitch (socket J1, USB-C, QFNs). Fabricator decides mask dams.',
}
def sh(cmd, **k): return subprocess.run(cmd, capture_output=True, text=True, **k)
out = []
def P(s=''): out.append(s)
P('# Verification report (no hardware)\n'); P('Generated by `tools/verify.py` on %s. Raw reports are in `docs/reports/`.\n' % TODAY)
# ---------------------------------------------------------------- ERC
shutil.rmtree('/tmp/erc_run', ignore_errors=True); os.makedirs('/tmp/erc_run')
sh(['xvfb-run', '-a', 'eeschema_do', 'run_erc', os.path.join(HW, 'sorx.kicad_sch'), '/tmp/erc_run'], timeout=600)
erc = open('/tmp/erc_run/sorx.erc').read(); shutil.copy('/tmp/erc_run/sorx.erc', os.path.join(REP, 'erc-report.txt'))
m = re.search(r'ERC messages: (\d+)\s+Errors (\d+)\s+Warnings (\d+)', erc)
P('## 1. Electrical rules check (schematic)\n')
P('- Tool: KiCad 7.0.11 ERC, run through `eeschema_do run_erc` (KiAuto) under a virtual display.')
P('- Result: **%s errors, %s warnings**, no waivers.' % (m.group(2), m.group(3)))
P('- Negative test: with a label removed from two pins and one label renamed, the same run reported 3 errors and 2 warnings, so the check does detect open pins and single-pin nets.\n')
# ---------------------------------------------------------------- netlist parity
r = sh([sys.executable, os.path.join(HERE, 'check_netlist.py')])
P('## 2. Netlist parity\n'); P('Schematic netlist exported with `kicad-cli sch export netlist` and compared with `tools/design.py`:\n'); P('```\n' + r.stdout.strip() + '\n```\n')
import pcbnew
from design import DESIGN
from gen_sch import resolve
b = pcbnew.LoadBoard(os.path.join(HW, 'sorx.kicad_pcb'))
bad = 0; pads = 0; fps = {f.GetReference(): f for f in b.GetFootprints()}
for p in DESIGN.parts.values():
    if not p.fp: continue
    f = fps.get(p.ref)
    if f is None: bad += 1; continue
    pn = resolve(p)
    for pad in f.Pads():
        want = pn.get(pad.GetNumber()) or ''
        pads += 1
        if pad.GetNetname() != want: bad += 1
P('Board pad nets compared with the same model: %d pads on %d footprints checked, **%d mismatches**.\n' % (pads, len(fps), bad))
# ---------------------------------------------------------------- DRC
rpt = os.path.join(REP, 'drc-report.txt')
pcbnew.WriteDRCReport(b, rpt, pcbnew.EDA_UNITS_MILLIMETRES, True)
txt = open(rpt).read()
secs = re.split(r'\n\*\* ', txt); viol = []; unconn = []
for s in secs:
    head = s.split('\n')[0]
    if not head.startswith('Found'): continue
    tgt = unconn if 'unconnected' in head else viol
    for mm_ in re.finditer(r'\[(\w+)\]: ([^\n]*)\n((?:    [^\n]*\n?)+)', s): tgt.append((mm_.group(1), mm_.group(2), mm_.group(3)))
def waived(v):
    w = WAIVERS.get(v[0])
    if w is None: return False
    return True if isinstance(w, str) else bool(re.search(w[1], v[2]))
def reason(k):
    w = WAIVERS.get(k); return w if isinstance(w, str) else w[0] if w else 'Needs a fix.'
cnt = collections.Counter(v[0] for v in viol); sev = {}
for v in viol:
    s_ = re.search(r'Severity: (\w+)', v[2]); sev.setdefault(v[0], collections.Counter())[s_.group(1) if s_ else '?'] += 1
unw = collections.Counter(v[0] for v in viol if not waived(v))
P('## 3. Design rules check (board)\n')
P('- Tool: KiCad 7.0.11 `pcbnew.WriteDRCReport`, all track errors reported, rules from `hw/sorx.kicad_pro`.')
P('- Unconnected items: **%d**.' % len(unconn))
P('- Violations: %d in %d categories; **%d unwaived**.\n' % (len(viol), len(cnt), sum(unw.values())))
if cnt:
    P('| Category | Count | Severity | Disposition | Reason |\n|---|---:|---|---|---|')
    for k, n in cnt.most_common():
        P('| `%s` | %d | %s | %s | %s |' % (k, n, ', '.join('%s %d' % kv for kv in sev[k].items()), 'Waived' if not unw.get(k) else '**%d NOT WAIVED**' % unw[k], reason(k)))
    P()
if unconn:
    nets = collections.Counter()
    for u in unconn:
        for mm_ in re.finditer(r'\[([^\]]+)\]', u[2]): nets[mm_.group(1)] += 1
    P('Unconnected nets: ' + ', '.join('%s (%d)' % kv for kv in nets.most_common(30)) + '\n')
# ---------------------------------------------------------------- pairs and power
import pairs, proj
rows = pairs.report(os.path.join(HW, 'sorx.kicad_pcb'))
P('## 4. Differential pairs as routed\n')
P('Pairs are routed by the autorouter as two nets of one class, side by side where space allows. Lengths include stubs to ESD parts on multi-drop nets.\n')
P('| Pair | Class | P mm | N mm | Skew mm | Vias P/N | Layers |\n|---|---|---:|---:|---:|---|---|')
for r_ in rows: P('| %s | %s | %.2f | %.2f | %.2f | %d/%d | %s |' % r_)
P('\nThe pairs are not length-matched. Length tuning is an open layout item (gate G3).\n')
pw = os.path.join(HW, 'build', 'power_widths.json')
if os.path.exists(pw):
    st = json.load(open(pw)); P('## 5. Power track widths after widening\n'); P('| Net | Length by width (mm of track at each width) | Narrowest |\n|---|---|---:|')
    for n in sorted(st, key=lambda n: -sum(st[n].values())):
        if sum(st[n].values()) < 3: continue
        P('| %s | %s | %s |' % (n, ', '.join('%s mm: %.0f' % (w, L) for w, L in sorted(st[n].items(), reverse=True)), min(st[n])))
    P()
# ---------------------------------------------------------------- fit check
fc = json.load(open(os.path.join(ROOT, 'mech', 'fit-check.json')))
P('## 6. Enclosure fit check\n'); P('Board assembly (PCB + component envelopes + SoM + heatsink + fan) placed in the enclosure model, `tools/gen_mech.py`. Drawing: `mech/fit-check.png`, model: `mech/sorx-assembly.step`.\n')
P('- Interference volume between enclosure and assembly: **%.3f mm3**.' % fc['max_interference_mm3'])
P('- All ports inside their openings with at least 0.25 mm margin: **%s**.' % ('yes' if fc['all_ports_aligned'] else 'NO'))
P('- Clearances: ' + ', '.join('%s = %s' % kv for kv in fc['clearances'].items()) + '.\n')
P('| Port | Wall | Part | Margin left / right / bottom / top (mm) | OK |\n|---|---|---|---|---|')
for p in fc['ports']: P('| %s | %s | %s | %.2f / %.2f / %.2f / %.2f | %s |' % (p['port'], p['wall'], p['ref'], p['margins']['left'], p['margins']['right'], p['margins']['bottom'], p['margins']['top'], 'yes' if p['ok'] else 'NO'))
P('\nComponent envelopes use nominal catalogue heights, not vendor 3D models.\n')
# ---------------------------------------------------------------- stock
import csv
P('## 7. BOM stock check (%s)\n' % TODAY)
rows = list(csv.DictReader(open(os.path.join(ROOT, 'bom', 'stock-check.csv'))))
chk = [r_ for r_ in rows if r_['Flag'] != 'NOT CHECKED']
P('%d of %d active/electromechanical line items were checked against distributor listings. The rest (%d lines, plus commodity resistors and capacitors) were **not checked** and are marked so in `bom/stock-check.csv`.\n' % (len(chk), len(rows), len(rows) - len(chk)))
P('| MPN | Qty/board | Stock seen | Lead time | Flag |\n|---|---:|---|---|---|')
for r_ in chk: P('| %s | %s | %s | %s | %s |' % (r_['MPN'], r_['Qty per board'], r_['Stock seen'], r_['Factory lead time'], r_['Flag']))
P()
gnd_open = sum(1 for u in unconn if '[GND]' in u[2]); sig_open = len(unconn) - gnd_open
passed = not (unconn or unw or bad or m.group(2) != '0')
out.insert(2, '## Result\n\n' + ('**Passed.**' if passed else '**Not passed: the board is not ready for fabrication.**') +
           ' ERC errors: %s. Pad-net mismatches: %d. Unwaived DRC violations: %d. Unconnected items: %d (%d signal/supply connections, %d GND pad groups without a path to the planes).\n' % (m.group(2), bad, sum(unw.values()), len(unconn), sig_open, gnd_open))
open(os.path.join(DOCS, 'verification-report.md'), 'w').write('\n'.join(out) + '\n')
print('ERC', m.group(2), m.group(3), '| parity mismatches', bad, '| DRC violations', len(viol), 'unwaived', dict(unw), '| unconnected', len(unconn))
